"""Generate firmware/ehg_node/src/replay_data.h from a converted record (digital injection source).

Usage: uv run python tools/make_replay.py data/converted/tpehgdb/tpehg1007.npz --record-id 12 [--seconds 120]
record_id is the index in that database's manifest.json; the backend uses it to find the source for H2/H4.
"""

import argparse
from pathlib import Path

import numpy as np

OUT = Path("firmware/ehg_node/src/replay_data.h")


def render(samples: np.ndarray, fs: float, record_id: int) -> str:
    n_frames, n_ch = samples.shape
    rows = ",\n".join("\t" + ", ".join(str(int(v)) for v in frame) for frame in samples)
    return f"""/* GENERATED by tools/make_replay.py - do not edit, do not commit. */
#pragma once
#include <stdint.h>

#define REPLAY_N_CH {n_ch}
#define REPLAY_N_FRAMES {n_frames}
#define REPLAY_FS_HZ {int(fs)}
#define REPLAY_RECORD_ID {record_id}

/* Only replay.c defines REPLAY_DEFINE_SAMPLES; everyone else gets just the constants. */
#ifdef REPLAY_DEFINE_SAMPLES
/* [REPLAY_N_FRAMES][REPLAY_N_CH], raw ADC units, frame-major */
static const int16_t replay_samples[REPLAY_N_FRAMES * REPLAY_N_CH] = {{
{rows}
}};
#endif
"""


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("npz")
    ap.add_argument("--record-id", type=int, required=True)
    ap.add_argument("--seconds", type=float, help="truncate (needed for 16 ch x 200 Hz: flash holds ~2 min)")
    a = ap.parse_args()
    rec = np.load(a.npz)
    s, fs = rec["samples"], float(rec["fs"])
    if a.seconds:
        s = s[: int(a.seconds * fs)]
    assert fs == int(fs), "firmware scheduler needs an integer sampling rate"
    OUT.write_text(render(s, fs, a.record_id))
    print(f"wrote {OUT}: {s.shape[0]} frames x {s.shape[1]} ch @ {fs} Hz, {s.nbytes / 1024:.0f} KiB")
