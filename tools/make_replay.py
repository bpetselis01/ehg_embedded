"""Bake one converted recording into the firmware as a C header.

Usage: uv run python tools/make_replay.py data/converted/tpehgdb/tpehg1007.npz [--seconds 120] [--bits 24] [--record-id N]
Normally run for you by `firmware/build.sh flash --record <npz>` (the built-in mode, docs/firmware.md).
record_id = that record's id in the DB's manifest.json (looked up automatically). Backend uses it to find the source for H2/H4.

PURPOSE: Puts 1 recording inside the firmware so the board can "play" it as a fake sensor with no laptop
  feeding it (stand-alone runs). The other mode, tools/feed.py, streams it over serial instead.
INPUT: data/converted/<db>/<record>.npz from tools/convert.py (arrays: docs/data/tpehgdb.md)
  uses `samples` int16 [n_frames, n_ch] and `fs`; record_id from the manifest.json next to it.
  e.g. tpehg1007.npz: samples int16 (35180, 3), first rows [[1093, 171, -748], [1145, 180, -790]];
       fs 20.0; --record-id 0
OUTPUT: firmware/ehg_node/src/replay_data.h (generated C text, not committed):
    #define REPLAY_N_CH 3 / REPLAY_N_FRAMES 35180 / REPLAY_FS_HZ 20 / REPLAY_RECORD_ID 0 / REPLAY_SAMPLE_BITS 16
    static const int16_t replay_samples[] = { 1093, 171, -748,  1145, 180, -790, ... }  (1 line per frame)
    --bits 24 (default for int32 records): int32_t array; firmware then sends 3-byte samples.
HOW: np.load the .npz, optionally cut to --seconds (flash is small: 16 ch x 200 Hz fits ~2 min),
  print numbers as C. fs must be a whole number (firmware scheduler).
ROLE IN THESIS: Dataset -> hardware bridge for digital injection (report 8.2). record_id baked in
  rides in every packet, so results trace back to the source.
BEFORE -> AFTER: Before: tools/convert.py output. After: firmware/ehg_node/src/replay_data.h,
  compiled by firmware/build.sh --record (CONFIG_EHG_BAKED_RECORD=y), read by firmware/ehg_node/src/replay.c.
  Tested by tests/test_make_replay.py.
"""

import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware/ehg_node/src/replay_data.h"


def render(samples: np.ndarray, fs: float, record_id: int, bits: int = 16) -> str:
    """Return the text of replay_data.h for these samples (one line of numbers per frame)."""
    lim = 2 ** (bits - 1)
    if samples.size and (samples.min() < -lim or samples.max() >= lim):
        raise ValueError(f"samples {samples.min()}..{samples.max()} don't fit {bits}-bit; use --bits 24")
    ctype = "int16_t" if bits == 16 else "int32_t"  # 24-bit values live in int32
    n_frames, n_ch = samples.shape
    rows = ",\n".join("\t" + ", ".join(str(int(v)) for v in frame) for frame in samples)
    return f"""/* GENERATED by tools/make_replay.py - do not edit, do not commit. */
#pragma once
#include <stdint.h>

#define REPLAY_N_CH {n_ch}
#define REPLAY_N_FRAMES {n_frames}
#define REPLAY_FS_HZ {int(fs)}
#define REPLAY_RECORD_ID {record_id}
#define REPLAY_SAMPLE_BITS {bits}

/* Only replay.c defines REPLAY_DEFINE_SAMPLES; everyone else gets just the constants. */
#ifdef REPLAY_DEFINE_SAMPLES
/* [REPLAY_N_FRAMES][REPLAY_N_CH], raw ADC units, frame-major */
static const {ctype} replay_samples[REPLAY_N_FRAMES * REPLAY_N_CH] = {{
{rows}
}};
#endif
"""


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("npz")
    ap.add_argument("--record-id", type=int, help="default: looked up in the manifest.json next to the npz")
    ap.add_argument("--seconds", type=float, help="truncate (needed for 16 ch x 200 Hz: flash holds ~2 min)")
    ap.add_argument("--bits", type=int, choices=(16, 24), help="sample width on the wire (default: 24 for int32 records, else 16)")
    a = ap.parse_args()
    rec = np.load(a.npz)
    s, fs = rec["samples"], float(rec["fs"])
    if a.seconds:
        s = s[: int(a.seconds * fs)]
    assert fs == int(fs), "firmware scheduler needs an integer sampling rate"
    bits = a.bits or (24 if s.dtype == np.int32 else 16)
    if a.record_id is None:
        sys.path.insert(0, str(ROOT))  # run as a script: make tools/ importable
        from tools.feed import record_id_for
        a.record_id = record_id_for(Path(a.npz))
    OUT.write_text(render(s, fs, a.record_id, bits))
    print(f"wrote {OUT}: {s.shape[0]} frames x {s.shape[1]} ch @ {fs} Hz, {bits}-bit, {s.size * (2 if bits == 16 else 4) / 1024:.0f} KiB")
