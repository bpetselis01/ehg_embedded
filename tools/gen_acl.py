"""Writes the Mosquitto ACL that pins every gateway to the nodes it serves.

PURPOSE: Closes the "a gateway can publish packets for ANY node id" gap of backend/mosquitto/acl (`topic write ehg/+/pkt`). Here each gateway may write only `ehg/<node>/pkt` for ITS nodes, plus its own status topic.
INPUT: --gateways FILE, a JSON object {"ehg-gw-01": ["EHG-93C0"], "ehg-gw-02": []}, OR --dsn <libpq string> to read the registry (registry.node.assigned_gateway, revoked gateways left out).
  --out FILE (default backend/mosquitto/acl.generated). e.g. uv run python tools/gen_acl.py --gateways deploy/acl/gateways.json --out /opt/ehg/etc/acl
OUTPUT: the ACL text (service identities ehg-bridge, ehg-ingest, ehg-viewer, ehg-exporter unchanged, then one stanza per gateway) and, on stdout, "changed" or "unchanged". Exit 1 and no file written on a bad id.
HOW: Ids must be plain ids (letters, digits, _ and -, at most 64), so no `+`, `#`, `/` or space can widen a grant; a wildcard in the data would otherwise grant more than the registry says. A gateway with no nodes gets its status topic only (it cannot publish packets
  until a node is assigned to it). The file is rewritten IN PLACE and only when the content changed, because a single-file bind mount follows the inode (a replaced file would leave the broker reading the old one); then send Mosquitto SIGHUP (deploy/crl-sync.sh does the same for the CRL).
  Output is deterministic (sorted) so a diff shows exactly what changed.
KNOWN LIMIT: Nothing assigns a node to a gateway yet (the registry column is there, the triage/enrolment code never sets it), so for now the JSON file is the source of truth. A new node means a new line in that file and a re-run.
ROLE IN THESIS: Least privilege on the gateway-to-broker boundary (docs/decisions/0008, docs/security.md). BEFORE -> AFTER: Before: any enrolled gateway could write packets under any node name. After: only its own.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parents[1]
sys.path.insert(0, str(ROOT))


def valid_id(value) -> bool:
    return isinstance(value, str) and re.fullmatch(r"[A-Za-z0-9_-]{1,64}", value) is not None


HEADER = """# GENERATED by tools/gen_acl.py: do not edit by hand (edit the gateways file or the registry, then re-run and SIGHUP Mosquitto).
# Same rules as backend/mosquitto/acl, except that a gateway may write packets only for the nodes listed under it.
# "user" is the CN of the client certificate (tools/pki.sh). Topics: ehg/<node>/pkt = packets, ehg/_gw/<gateway>/status = online/offline.

user ehg-bridge
topic read ehg/+/pkt
topic read ehg/_gw/+/status

user ehg-ingest
topic read ehg/+/pkt

user ehg-viewer
topic read ehg/+/pkt

user ehg-exporter
topic read $SYS/broker/clients/connected
topic read $SYS/broker/clients/total
topic read $SYS/broker/messages/received
topic read $SYS/broker/messages/sent
topic read $SYS/broker/bytes/received
topic read $SYS/broker/bytes/sent
topic read $SYS/broker/publish/messages/dropped
topic read $SYS/broker/store/messages/count
topic read $SYS/broker/uptime
"""
SERVICES = {"ehg-bridge", "ehg-ingest", "ehg-viewer", "ehg-exporter"}


def render(assignments: dict[str, list[str]]) -> str:
    """ACL text for {gateway id: [node ids]}. Raises ValueError for an id that is not a plain id, or a gateway named like a service identity."""
    out = [HEADER]
    for gw in sorted(assignments):
        nodes = assignments[gw]
        if not valid_id(gw):
            raise ValueError(f"gateway id {gw!r} is not a plain id")
        if gw in SERVICES:
            raise ValueError(f"gateway id {gw!r} collides with a service identity")
        if not isinstance(nodes, list) or not all(valid_id(n) for n in nodes):
            raise ValueError(f"nodes of {gw!r} must be a list of plain ids, got {nodes!r}")
        out.append(f"user {gw}")
        out.extend(f"topic write ehg/{n}/pkt" for n in sorted(set(nodes)))
        out.append(f"topic write ehg/_gw/{gw}/status\n")
    return "\n".join(out)


def from_registry(dsn: str) -> dict[str, list[str]]:
    """Non-revoked gateways and their assigned nodes, from the registry tables."""
    import psycopg
    with psycopg.connect(dsn, connect_timeout=5) as c:
        gws = {r[0]: [] for r in c.execute("SELECT id FROM registry.gateway WHERE revoked_at IS NULL")}
        for node, gw in c.execute("SELECT id, assigned_gateway FROM registry.node WHERE assigned_gateway IS NOT NULL"):
            if gw in gws:
                gws[gw].append(node)
    return gws


def write_in_place(path: Path, text: str) -> bool:
    """Write only when different, into the SAME file. True if it changed."""
    if path.exists() and path.read_text() == text:
        return False
    with open(path, "w") as f:
        f.write(text)
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--gateways", type=Path)
    src.add_argument("--dsn")
    ap.add_argument("--out", type=Path, default=ROOT / "backend/mosquitto/acl.generated")
    a = ap.parse_args(argv)
    try:
        data = json.loads(a.gateways.read_text()) if a.gateways else from_registry(a.dsn)
        if not isinstance(data, dict):
            raise ValueError("the gateways file must be a JSON object {gateway: [nodes]}")
        text = render(data)
    except (ValueError, OSError) as e:
        print(f"gen_acl: {e}", file=sys.stderr)
        return 1
    print("changed" if write_in_place(a.out, text) else "unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
